CREATE TABLE IF NOT EXISTS acceptance_checks (
 id TEXT PRIMARY KEY,
 section TEXT NOT NULL,
 title TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 priority TEXT NOT NULL DEFAULT 'critical',
 requires_auth BOOLEAN NOT NULL DEFAULT false,
 status TEXT NOT NULL DEFAULT 'unknown' CHECK (status IN ('verified','failed','blocked','unknown')),
 evidence_method TEXT NOT NULL DEFAULT '',
 evidence_url TEXT NOT NULL DEFAULT '',
 evidence_notes TEXT NOT NULL DEFAULT '',
 environment TEXT NOT NULL DEFAULT 'staging',
 tested_commit TEXT NOT NULL DEFAULT '',
 verified_at TIMESTAMPTZ,
 last_updated TIMESTAMPTZ NOT NULL DEFAULT now(),
 next_steps JSONB NOT NULL DEFAULT '[]'::jsonb,
 sort_order INTEGER NOT NULL DEFAULT 0,
 is_baseline BOOLEAN NOT NULL DEFAULT false,
 pr_number INTEGER
)